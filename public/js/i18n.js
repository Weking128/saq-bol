  const LANGS = ['kk', 'ru'];
  let lang = SB.store.get('lang');
  if (!LANGS.includes(lang)) lang = (navigator.language || '').toLowerCase().startsWith('kk') ? 'kk' : 'ru';

  function t(key, vars) {
    const v = DICT[lang][key] ?? DICT.ru[key] ?? key;
    if (typeof v !== 'string' || !vars) return v;
    return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  }

  function setLang(l) {
    if (!LANGS.includes(l)) return;
    lang = l;
    SB.store.set('lang', l);
    document.documentElement.lang = l;
  }

  // Переключатель «ҚАЗ | РУС»
  function langSwitch(onChange) {
    const { h } = SB;
    const box = h('div', { class: 'lang-switch', role: 'group', 'aria-label': 'Тіл / Язык' });
    for (const [code, label] of [['kk', 'ҚАЗ'], ['ru', 'РУС']]) {
      box.append(h('button', {
        type: 'button', lang: code, 'aria-pressed': String(lang === code),
        onclick: () => { if (lang !== code) { setLang(code); onChange(code); } },
      }, label));
    }
    return box;
  }

  document.documentElement.lang = lang;
  Object.defineProperty(SB, 'lang', { get: () => lang });
  // Миссии и памятка на текущем языке (данные — в missions.js и missions.kk.js)
  Object.defineProperty(SB, 'MISSIONS', { get: () => (SB.MISSIONS_BY_LANG || {})[lang] || (SB.MISSIONS_BY_LANG || {}).ru });
  Object.defineProperty(SB, 'MEMO', { get: () => (SB.MEMO_BY_LANG || {})[lang] || (SB.MEMO_BY_LANG || {}).ru });
  // Облегчённая версия для 1–6 классов
  Object.defineProperty(SB, 'JUNIOR_MISSIONS', { get: () => (SB.JUNIOR_MISSIONS_BY_LANG || {})[lang] || (SB.JUNIOR_MISSIONS_BY_LANG || {}).ru });
  Object.defineProperty(SB, 'JUNIOR_MEMO', { get: () => (SB.JUNIOR_MEMO_BY_LANG || {})[lang] || (SB.JUNIOR_MEMO_BY_LANG || {}).ru });
  Object.assign(SB, { t, setLang, langSwitch, LANGS });
